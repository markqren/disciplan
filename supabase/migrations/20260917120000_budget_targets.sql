-- Agent SQL tool: owner-scoped read view (fail closed when GUC unset).
CREATE OR REPLACE VIEW insight_ro.budget_targets AS
SELECT year, category_id, pct_of_income
  FROM disciplan.budget_targets bt
 WHERE bt.household_id IN (
   SELECT p.household_id FROM disciplan.profiles p
    WHERE p.owner = current_setting('disciplan.insight_owner', true)
 );
