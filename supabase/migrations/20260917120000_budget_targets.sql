-- FEA: Persist Income Statement budget targets (% of income) for app + newsletter agent.
-- Household-scoped (one target set per household per year). Exposed read-only via insight_ro.

CREATE TABLE IF NOT EXISTS disciplan.budget_targets (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id  BIGINT NOT NULL REFERENCES disciplan.households(id),
  owner         TEXT,
  year          INT NOT NULL,
  category_id   TEXT NOT NULL,
  pct_of_income NUMERIC NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (household_id, year, category_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON disciplan.budget_targets TO authenticated;
GRANT ALL ON disciplan.budget_targets TO service_role;
GRANT USAGE, SELECT ON SEQUENCE disciplan.budget_targets_id_seq TO authenticated;
GRANT ALL ON SEQUENCE disciplan.budget_targets_id_seq TO service_role;

ALTER TABLE disciplan.budget_targets ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "budget_targets_all" ON disciplan.budget_targets;
CREATE POLICY "budget_targets_all" ON disciplan.budget_targets
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE INDEX IF NOT EXISTS budget_targets_household_year_idx
  ON disciplan.budget_targets (household_id, year);

